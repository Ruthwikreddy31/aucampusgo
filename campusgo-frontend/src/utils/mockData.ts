const categoryFor = (id: number, name: string) => ({
  id,
  name,
  description: '',
  imageUrl: '',
  active: true,
})

const campusProduct = (
  id: number,
  shopIndex: number,
  name: string,
  categoryId: number,
  categoryName: string,
  price: number,
  stock: number,
  imageUrl: string,
  description = `${name} available at ${mockShops[shopIndex].name}.`,
): Product => ({
  id,
  shopId: mockShops[shopIndex].id,
  categoryId,
  name,
  description,
  price,
  imageUrl,
  available: stock > 0,
  active: true,
  stock,
  shop: mockShops[shopIndex],
  category: categoryFor(categoryId, categoryName),
  createdAt: '',
  updatedAt: '',
})

